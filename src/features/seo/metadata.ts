/* ---------------------------------------------------------------------------
   Page metadata: one builder, so every indexable page says the same things

   Next merges metadata **shallowly**: a page that sets `openGraph` replaces the
   layout's whole `openGraph` object, image and site name included
   (`node_modules/next/dist/docs/01-app/03-api-reference/04-functions/
   generate-metadata.md`, "Merging"). So a page never writes those objects by
   hand. It calls `pageMetadata()` and gets the full set: title, description,
   canonical, Open Graph and Twitter.

   **Canonical.** `path` is the clean path, with no query string. `/tires`,
   `/wheels` and `/accessories` pass their bare path whatever filters the URL
   carries, and a product page passes `/products/<slug>` whatever `?qty=` says,
   so every search, filter and quantity URL points at one address (owner brief,
   2026-09-30). It resolves against `metadataBase` (`SITE_URL`), set once in the
   root layout.

   **Link previews** (owner, 2026-09-30): one branded dark card for the site,
   and the product's own photo on a product page. `image` defaults to the site
   card; a product page passes its own.
   --------------------------------------------------------------------------- */

import type { Metadata } from "next";

import { SITE } from "@/lib/site";

/** The standard link-preview size. Both cards are drawn at it. */
export const PREVIEW_SIZE = { width: 1200, height: 630 } as const;

export interface PreviewImage {
  /** A path from the site root, or an absolute URL. */
  url: string;
  alt: string;
  type: "image/png" | "image/jpeg";
}

/** The site card, generated by `src/app/opengraph-image.tsx`. */
export const SITE_CARD: PreviewImage = {
  url: "/opengraph-image",
  alt: `${SITE.name}: ${SITE.tagline}`,
  type: "image/png",
};

/** Canadian English. The `<html lang>` attribute is a separate matter and is
 *  not set here. */
const LOCALE = "en_CA";

export interface PageSeo {
  /** The page's own title. The root template appends the site name unless
   *  `absoluteTitle` is set. */
  title: string;
  /** Use `title` as the whole `<title>`, with no template. The home page. */
  absoluteTitle?: boolean;
  description: string;
  /** The clean canonical path: leading slash, no query string, no fragment. */
  path: string;
  image?: PreviewImage;
}

export function pageMetadata({
  title,
  absoluteTitle = false,
  description,
  path,
  image = SITE_CARD,
}: PageSeo): Metadata {
  const images = [{ ...image, ...PREVIEW_SIZE }];
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE.name,
      locale: LOCALE,
      url: path,
      title,
      description,
      images,
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images,
    },
  };
}

/**
 * What the root layout hands every route that sets no Open Graph of its own:
 * the 404, `/styleguide`, the admin and the payment pages. A payment link sent
 * by text still unfurls as the shop's card rather than as a bare URL.
 */
export const SITE_PREVIEW: Pick<Metadata, "openGraph" | "twitter"> = {
  openGraph: {
    type: "website",
    siteName: SITE.name,
    locale: LOCALE,
    images: [{ ...SITE_CARD, ...PREVIEW_SIZE }],
  },
  twitter: {
    card: "summary_large_image",
    images: [{ ...SITE_CARD, ...PREVIEW_SIZE }],
  },
};
